export const getEnrichedListings = () => {
  return pgListings.map(item => {
    const is1BHK = item.name.toLowerCase().includes('1bhk') || item.name.toLowerCase().includes('1 bhk') || (item.desc || '').toLowerCase().includes('1bhk');
    const is2BHK = item.name.toLowerCase().includes('2bhk') || item.name.toLowerCase().includes('2 bhk') || (item.desc || '').toLowerCase().includes('2bhk');
    
    let roomType = 'shared';
    let roomTypeLabel = 'Shared Room';
    if (is1BHK) {
      roomType = '1bhk';
      roomTypeLabel = '1 BHK';
    } else if (is2BHK) {
      roomType = '2bhk';
      roomTypeLabel = '2 BHK';
    } else if (item.sharing === 1) {
      roomType = 'single';
      roomTypeLabel = 'Single Room';
    }

    const dayRate = is1BHK ? 1199 : (item.sharing === 1 ? 799 : (item.sharing === 2 ? 499 : (item.sharing === 3 ? 399 : 349)));
    const weekRate = is1BHK ? 4999 : (item.sharing === 1 ? 3499 : (item.sharing === 2 ? 2199 : (item.sharing === 3 ? 1799 : 1499)));
    const monthRate = item.price || (is1BHK ? 18000 : 7499);
    const depositAmount = item.deposit || (is1BHK ? 18000 : (item.sharing === 1 ? 5000 : 3000));
    const depositDisplay = item.depositDisplay || `₹${depositAmount.toLocaleString('en-IN')}`;

    return {
      ...item,
      roomType,
      roomTypeLabel,
      deposit: depositAmount,
      depositDisplay,
      stayRates: {
        day: dayRate,
        dayDisplay: `₹${dayRate.toLocaleString('en-IN')}`,
        week: weekRate,
        weekDisplay: `₹${weekRate.toLocaleString('en-IN')}`,
        month: monthRate,
        monthDisplay: `₹${monthRate.toLocaleString('en-IN')}`,
      },
      stayBenefits: {
        day: 'Free hot Kerala breakfast • Zero deposit',
        week: 'Homestyle breakfast & dinner • Flexible lease',
        month: is1BHK ? '18k Rent • 18k Deposit • Near Infosys' : '3x Kerala meals daily + evening chai • Full access',
      },
      amenitiesSummary: [
        '3 Times Kerala Food',
        'High-Speed WiFi & Power Backup',
        'Lounge Area & Entertainment Zone',
        'Washing Machine & 24/7 Hot Water',
        'CCTV & 24/7 Caretaker',
        'Self Cooking Area'
      ],
      availabilityStatus: 'Move-in Ready',
    };
  });
};

export const allEnrichedListings = getEnrichedListings();
